# --customizationfile path
# use the given ini file as GUI customization

# --authdbdirectory path
# use the given directory for authentication database

# --code path
# run the given python file on load

# --py-args arguments
# arguments for python. These arguments will be available for each python execution via 'sys.argv' including the file specified by '--code'. All arguments till '--' are passed to python and ignored by QGIS.

# --defaultui
# start by resetting user ui settings to default

# --profile name
# load a named profile from the user's profiles folder.

# --profiles-path path
# path to store user profile folders. Will create profiles inside a {path}\profiles folder

# --openclprogramfolder
# path to the folder containing the sources for OpenCL programs.